#!/usr/bin/env python3
"""Probe: :tsinstall and :tsupdate build the pinned grammar revision.

A grammar's lockfile revision is what makes two machines installing "python"
build the same parser. The pin has to survive four hops to matter: the vendored
lockfile -> registry.lua -> the native install metadata -> the shell script the
editor really runs. This probe drives the real binary in a pty and reads back
what each hop produced.

`git` and the compiler are stubbed on PATH, the way the wakatime probe stubs its
cli: no grammar is cloned from the network and no compiler runs, but every git
invocation the install script makes is recorded with its arguments, and the
library file the script's success check looks for is written by the stub. The
command is unmodified -- it is generated by the editor and run by a real shell --
so a pin that never made it into the script, or a quoting slip that breaks the
fetch, shows up here.

Scenes (each in its own config dir and install prefix):

  * `:tsupdate` with nothing installed: no install panel, no job log and no git
    run (the wording of the refusal is pinned by test_tree_sitter_update.cpp,
    where the message channel is readable);
  * `:tsinstall python`: the status panel opens, the script clones, fetches
    `<pin>` and checks the commit out, then finishes (its own `success` marker
    lands in the job log, which a `set -e` abort before it would have prevented);
  * the same install where the shallow fetch is refused: the script falls back to
    a full fetch of the tags and still finishes on the pin;
  * `:tsupdate python`: an installed parser is rebuilt, and that means the same
    clone plus fetch plus checkout of the pin a second time;
  * `:tsupdate crystal`, a registry grammar nvim-treesitter has no pin for: the
    same refusal -- nothing is cloned and no job is queued.

Usage: test/treesitter_pin_probe.py [path-to-jot-binary] [--dump]
Exit codes: 0 pass, 1 fail, 2 binary missing.
"""
from __future__ import annotations

import glob
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pty_screen import run_in_pty  # noqa: E402

ROOT = "/tmp/jot_treesitter_pin_probe"
# The stub toolchain and its record of every git call.
SHIM = ROOT + "/bin"
GIT_LOG = ROOT + "/git.log"
WORK = ROOT + "/work"
# Data and cache roots are moved into the probe so a parser the machine already
# has in ~/.local/share/jot/treesitter cannot answer "is it installed?" for us.
DATA = ROOT + "/data"
CACHE = ROOT + "/cache"
FILE = "notes.txt"

# Every scene gets its own config dir (so its own job log) and its own install
# prefix, which is also how "installed" is staged for the :tsupdate scenes.
CFG = {name: ROOT + "/cfg-" + name for name in
       ("nothing", "install", "fallback", "update", "unpinned")}
PREFIX = {name: ROOT + "/prefix-" + name for name in CFG}

# Commands ride the Ctrl+P palette, the spelling this editor's input mode uses
# (typing ":tsinstall" into the buffer would just insert it as text).
PALETTE = b"\x10"
ENTER = b"\r"

PYTHON = "python"
# A registry grammar nvim-treesitter ships no lockfile entry for, so there is no
# revision to move to and the editor has to say that.
UNPINNED = "crystal"

# The stub git: clone writes the source tree a grammar repository would have,
# install calls are recorded, and the shallow fetch can be made to fail (for the
# fallback scene) by an environment variable the probe sets. Everything else is
# the editor's own git integration asking about a workspace that is not a
# repository, which is answered the way git does: exit 128.
STUB_GIT = """#!/bin/sh
install_call=""
if [ "$1" = "clone" ]; then
  install_call=1
fi
if [ "$1" = "-C" ]; then
  case "$2" in
    *jot-tree-sitter-*) install_call=1 ;;
  esac
fi
if [ -z "$install_call" ]; then
  echo "fatal: not a git repository (or any of the parent directories): .git" >&2
  exit 128
fi
printf '%s\\n' "$*" >> "$JOT_TS_PROBE_LOG"
if [ "$1" = "clone" ]; then
  dest=""
  for arg in "$@"; do
    dest=$arg
  done
  mkdir -p "$dest/src" "$dest/queries" || exit 1
  printf 'int jot_probe_parser_stub;\\n' > "$dest/src/parser.c"
  printf '; stub query\\n' > "$dest/queries/highlights.scm"
  exit 0
fi
shift 2
if [ "$1" = "fetch" ] && [ -n "$JOT_TS_PROBE_FAIL_SHALLOW" ]; then
  for arg in "$@"; do
    if [ "$arg" = "--depth" ]; then
      exit 1
    fi
  done
fi
exit 0
"""

# The stub compiler: it records the call and writes whatever file `-o` names,
# which is all the install script checks (a non-empty parser library).
STUB_CC = """#!/bin/sh
printf '%s|%s\\n' "$(basename "$0")" "$*" >> "$JOT_TS_PROBE_LOG"
out=""
prev=""
for arg in "$@"; do
  [ "$prev" = "-o" ] && out="$arg"
  prev="$arg"
done
[ -n "$out" ] && printf 'probe stub object\\n' > "$out"
exit 0
"""


def command(name: str, argument: str = "") -> bytes:
    """The palette accepts a whole command line: type it, press Enter, it runs."""
    line = name if not argument else name + " " + argument
    return PALETTE + line.encode() + ENTER


def locked_revision(language: str) -> str:
    """The pin the editor itself ships for `language`, read from its Lua data."""
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "runtime", "lua", "treesitter", "lockfile.lua")
    with open(path) as fh:
        text = fh.read()
    match = re.search(r'\["%s"\] = "([0-9a-f]+)"' % re.escape(language), text)
    if match is None:
        raise SystemExit("no pinned revision for %s in %s" % (language, path))
    return match.group(1)


def git_calls() -> list[str]:
    if not os.path.exists(GIT_LOG):
        return []
    with open(GIT_LOG, errors="replace") as fh:
        return [line.strip() for line in fh if line.strip()]


def job_logs(scene: str) -> str:
    text = ""
    for path in sorted(glob.glob(os.path.join(CFG[scene], "logs", "install_ts-*.log"))):
        with open(path, errors="replace") as fh:
            text += fh.read()
    return text


def modal_title_row(screen) -> str:
    """The status panel's title row, or "" when the panel is not on screen.

    ui_draw_panel_title paints " Tree-sitter" over the panel's top border, so the
    row is recognisable by the box-drawing glyph before the text -- which is what
    tells the panel apart from a message line that happens to mention it.
    """
    for row in screen.text().splitlines():
        if " Tree-sitter " in row and "─" in row:
            return row.strip()
    return ""


def run(binary: str, scene: str, keys: bytes, extra_env: dict | None = None, after: float = 4.5):
    env = {
        "PATH": SHIM + ":" + os.environ.get("PATH", ""),
        "XDG_DATA_HOME": DATA,
        "XDG_CACHE_HOME": CACHE,
        "JOT_TREESITTER_PREFIX": PREFIX[scene],
        "JOT_TS_PROBE_LOG": GIT_LOG,
        # Pin the toolchain to the stubs: `cc=${CC:-cc}` only finds them when no
        # CC/CXX is already exported in this machine's environment.
        "CC": "cc",
        "CXX": "c++",
    }
    env.update(extra_env or {})
    return run_in_pty(binary, [os.path.join(WORK, FILE)], keys, settle=3.0, after=after,
                      cfg=CFG[scene], cwd=WORK, cols=110, rows=26, env=env)


def install_command(git_calls: list[str], language: str) -> dict:
    """Split one install script's git calls into the steps under test.

    `fetch` and `checkout` are the only calls carrying `-C <work>`; the clone is
    the one calling `clone`.
    """
    steps = {"clone": [], "fetch": [], "checkout": []}
    for call in git_calls:
        if call.startswith("clone "):
            steps["clone"].append(call)
        elif " fetch " in call:
            steps["fetch"].append(call)
        elif " checkout " in call:
            steps["checkout"].append(call)
    steps["language"] = language
    return steps


def main() -> int:
    binary = sys.argv[1] if len(sys.argv) > 1 else "build/apps/jot/jot"
    dump = "--dump" in sys.argv
    if not os.path.exists(binary):
        print("treesitter pin probe: SKIP - no binary at %s" % binary)
        return 2
    binary = os.path.abspath(binary)

    for path in (ROOT,):
        shutil.rmtree(path, ignore_errors=True)
    os.makedirs(SHIM)
    os.makedirs(WORK)
    with open(os.path.join(WORK, FILE), "w") as fh:
        fh.write("plain text buffer: no grammar is loaded for it\n")
    for name in CFG:
        os.makedirs(PREFIX[name])
    for name, body in (("git", STUB_GIT), ("cc", STUB_CC), ("c++", STUB_CC)):
        path = os.path.join(SHIM, name)
        with open(path, "w") as fh:
            fh.write(body)
        os.chmod(path, 0o755)

    pin = locked_revision(PYTHON)
    failures: list[str] = []

    def check(name: str, ok: bool, detail: str) -> None:
        if not ok:
            failures.append("%s (%s)" % (name, detail))
        print("treesitter pin probe: %s %s - %s" % (name, "ok" if ok else "FAIL", detail))

    # ── Scene 1: nothing installed, so nothing to update ─────────────────────
    screen = run(binary, "nothing", command("tsupdate"))
    if dump:
        print("=== :tsupdate with no parsers ===")
        print(screen.text())
    check("an empty update opens no install panel", modal_title_row(screen) == "",
          modal_title_row(screen) or "no panel")
    check("an empty update queues no job", job_logs("nothing") == "",
          job_logs("nothing").strip().splitlines()[-2:])
    check("nothing was cloned for an empty update",
          git_calls() == [],
          git_calls()[:3])

    # ── Scene 2: :tsinstall python builds the pin ────────────────────────────
    screen = run(binary, "install", command("tsinstall", PYTHON))
    if dump:
        print("=== :tsinstall python ===")
        print(screen.text())
    check("the install opens the status panel", modal_title_row(screen) != "",
          modal_title_row(screen) or screen.text().splitlines()[-2:])
    calls = git_calls()
    steps = install_command(calls, PYTHON)
    check("the grammar is cloned once", len(steps["clone"]) == 1, calls[:4])
    check("the pinned revision is fetched",
          any(call.endswith(" fetch --depth 1 origin " + pin) for call in steps["fetch"]),
          steps["fetch"])
    check("the pinned revision is checked out",
          any(call.endswith(" checkout --detach " + pin) for call in steps["checkout"]),
          steps["checkout"])
    check("the pin is the one the editor ships", pin in " ".join(calls), pin)
    log = job_logs("install")
    check("the install script reported success",
          "[jot:treesitter] success python" in log and "[jot:treesitter] pin python" in log,
          log.strip().splitlines()[-3:])
    library = os.path.join(PREFIX["install"], "parsers", "libtree-sitter-python.so")
    check("the parser library was written", os.path.exists(library), library)

    # ── Scene 3: a refused shallow fetch falls back to the tags ──────────────
    before = len(calls)
    screen = run(binary, "fallback", command("tsinstall", PYTHON),
                 {"JOT_TS_PROBE_FAIL_SHALLOW": "1"})
    if dump:
        print("=== :tsinstall python, shallow fetch refused ===")
        print(screen.text())
    calls = git_calls()[before:]
    steps = install_command(calls, PYTHON)
    check("the refused shallow fetch is followed by a full fetch",
          any(call.endswith(" fetch --depth 1 origin " + pin) for call in steps["fetch"])
          and any(call.endswith(" fetch --tags origin") for call in steps["fetch"]),
          steps["fetch"])
    check("the fallback still lands on the pin",
          any(call.endswith(" checkout --detach " + pin) for call in steps["checkout"]),
          steps["checkout"])
    check("the script still finished after the fallback",
          "[jot:treesitter] success python" in job_logs("fallback"),
          job_logs("fallback").strip().splitlines()[-2:])

    # ── Scene 4: :tsupdate rebuilds an installed parser at its pin ───────────
    before = len(git_calls())
    screen = run(binary, "update", command("tsupdate", PYTHON),
                 {"JOT_TREESITTER_PREFIX": PREFIX["install"]})
    if dump:
        print("=== :tsupdate python ===")
        print(screen.text())
    check("the update opens the status panel", modal_title_row(screen) != "",
          modal_title_row(screen) or screen.text().splitlines()[-2:])
    calls = git_calls()[before:]
    steps = install_command(calls, PYTHON)
    check("the update clones and fetches the pin again",
          len(steps["clone"]) == 1
          and any(call.endswith(" fetch --depth 1 origin " + pin) for call in steps["fetch"]),
          calls[:4])
    check("the update checks the pin out",
          any(call.endswith(" checkout --detach " + pin) for call in steps["checkout"]),
          steps["checkout"])
    check("the update job finished",
          "[jot:treesitter] success python" in job_logs("update"),
          job_logs("update").strip().splitlines()[-2:])

    # ── Scene 5: a grammar with no upstream pin says so ──────────────────────
    before = len(git_calls())
    screen = run(binary, "unpinned", command("tsupdate", UNPINNED))
    if dump:
        print("=== :tsupdate %s ===" % UNPINNED)
        print(screen.text())
    check("an unpinned grammar opens no install panel", modal_title_row(screen) == "",
          modal_title_row(screen) or "no panel")
    check("an unpinned grammar queues no job", job_logs("unpinned") == "",
          job_logs("unpinned").strip().splitlines()[-2:])
    check("nothing was cloned for an unpinned grammar",
          len(git_calls()) == before,
          git_calls()[before:])

    if failures:
        print("treesitter pin probe: FAIL")
        for failure in failures:
            print("  - %s" % failure)
        return 1
    print("treesitter pin probe: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
