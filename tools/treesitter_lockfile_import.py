#!/usr/bin/env python3
"""Regenerate runtime/lua/treesitter/lockfile.lua from nvim-treesitter's lockfile.

nvim-treesitter records the commit each grammar was last verified at, and
`:TSInstall`/`:TSUpdate` build that commit rather than whatever the default
branch holds the day a user installs. Without it, two machines installing the
same parser get different parsers, and a grammar that lands a broken release
breaks `:tsinstall` for everyone until someone notices.

The data is vendored because :tsinstall already needs the network; making the
pin itself a second download would mean an unreachable lockfile URL silently
changes which revision gets built. This tool is the only writer of that file:

    tools/treesitter_lockfile_import.py                     # fetch upstream
    tools/treesitter_lockfile_import.py --lockfile path.json
    tools/treesitter_lockfile_import.py --check              # CI: is it current?

Only the languages the registry ships are written, so the file covers exactly
what the editor can install. A registry language the lockfile does not carry
(the registry has a few grammar forks nvim-treesitter does not ship) gets no
entry and keeps cloning its default branch; the tool prints those, so a gap is
visible at generation time instead of being discovered as a drifting parser.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "runtime", "lua", "treesitter", "registry.lua")
OUTPUT = os.path.join(ROOT, "runtime", "lua", "treesitter", "lockfile.lua")
LOCKFILE_URL = ("https://raw.githubusercontent.com/nvim-treesitter/nvim-treesitter"
                "/master/lockfile.json")

HEADER = """\
-- Pinned grammar revisions, one per language this editor can install.
--
-- Generated by tools/treesitter_lockfile_import.py from nvim-treesitter's
-- lockfile: %(url)s
-- Fetched %(date)s. Do not hand-edit; rerun the tool to refresh.
--
-- A revision is the commit the grammar was verified at, so :tsinstall and
-- :tsupdate build the same parser on every machine instead of whatever the
-- default branch happens to hold that day. A language absent from this table
-- is one nvim-treesitter does not ship (the registry carries a few forks of its
-- own): it clones its default branch, as every language did before pinning.
return {
"""


def registry_languages() -> list[str]:
    """The language names of registry.lua's data table, in file order."""
    with open(REGISTRY) as fh:
        text = fh.read()
    names = re.findall(r'^\s*\{"([A-Za-z0-9_]+)"', text, re.M)
    if not names:
        raise SystemExit("no languages found in %s" % REGISTRY)
    return names


def load_lockfile(path: str, url: str) -> dict[str, str]:
    if path:
        with open(path, "rb") as fh:
            raw = fh.read()
    else:
        with urllib.request.urlopen(url, timeout=60) as response:
            raw = response.read()
    data = json.loads(raw.decode("utf-8"))
    revisions = {}
    for name, entry in data.items():
        revision = entry.get("revision") if isinstance(entry, dict) else None
        if revision:
            revisions[name] = revision
    return revisions


def render(revisions: dict[str, str], names: list[str], url: str) -> tuple[str, list[str]]:
    missing = [name for name in names if name not in revisions]
    pinned = sorted(name for name in names if name in revisions)
    out = [HEADER % {"url": url, "date": datetime.date.today().isoformat()}]
    for name in pinned:
        out.append('  ["%s"] = "%s",\n' % (name, revisions[name]))
    out.append("}\n")
    return "".join(out), missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lockfile", default="", help="read this lockfile JSON instead of fetching")
    parser.add_argument("--url", default=LOCKFILE_URL, help="lockfile URL to fetch")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; fail if the file on disk differs")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    names = registry_languages()
    revisions = load_lockfile(args.lockfile, args.url)
    body, missing = render(revisions, names, args.url)

    if args.check:
        current = open(OUTPUT).read() if os.path.exists(OUTPUT) else ""
        # The date line moves with every run, so compare the entries only.
        strip = lambda text: [l for l in text.splitlines() if l.strip() and not l.startswith("--")]
        if strip(current) != strip(body):
            print("treesitter lockfile import: FAIL - %s is stale" % os.path.relpath(OUTPUT, ROOT))
            return 1
        print("treesitter lockfile import: PASS - %s matches upstream" % os.path.relpath(OUTPUT, ROOT))
        return 0

    with open(OUTPUT, "w") as fh:
        fh.write(body)
    if not args.quiet:
        print("wrote %s: %d pinned revision(s) of %d registry language(s)"
              % (os.path.relpath(OUTPUT, ROOT), len(revisions) - len(missing), len(names)))
        if missing:
            print("no upstream pin (clones the default branch): %s" % ", ".join(sorted(missing)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
